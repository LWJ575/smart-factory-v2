/* 颜色定义 (RGB565) */
#define COL_BG      0x2104   /* 深蓝背景 #1a1a2e */
#define COL_PANEL   0x18E3   /* 面板背景 #16213e */
#define COL_BORDER   0x1B1B   /* 边框 #0f3460 */
#define COL_TITLE    0xC618   /* 标题白色 #E0E0E0 */
#define COL_LABEL    0x8410   /* 标签灰色 #888888 */
#define COL_TEMP    0xFB56   /* 温度红色 #FF6B6B */
#define COL_LIGHT   0xFFE0   /* 光照黄色 #F0F066 */
#define COL_MOTOR   0x67EC   /* 电机青色 #4ECDC4 */
#define COL_OK      0x67EC   /* 正常青色 */
#define COL_ERR     0xF800   /* 错误红色 */
#define COL_GREEN   0x07E0
#define COL_BAR_BG  0x39E7   /* 进度条背景 #333344 */

/* 仪表盘区域坐标 */
#define TITLE_Y       4

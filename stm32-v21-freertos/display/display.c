/* ==================== 底层绘制函数 ==================== */

/* 填充矩形区域 */
void lcd_fill_rect(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2, uint16_t color)
{
    uint32_t total = (uint32_t)(x2 - x1 + 1) * (y2 - y1 + 1);
    lcd_set_window(x1, y1, x2, y2);
    while (total--) {
        LCD_RAM = color;
    }
}

/* 画矩形边框 */
void lcd_draw_rect(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2, uint16_t color)
{
    lcd_draw_hline(x1, y1, x2, color);
    lcd_draw_hline(x1, y2, x2, color);
    lcd_fill_rect(x1, y1, x1, y2, color);
    lcd_fill_rect(x2, y1, x2, y2, color);
}

/* 画水平线 */
void lcd_draw_hline(uint16_t x1, uint16_t y, uint16_t x2, uint16_t color)
{
    lcd_fill_rect(x1, y, x2, y, color);
}

/* 在 (x, y) 绘制单个字符 (8x16) */
void lcd_show_char(uint16_t x, uint16_t y, char ch, uint16_t fg, uint16_t bg)
{
    const uint8_t *glyph;
    int row, col;

    if ((uint8_t)ch < 32 || (uint8_t)ch > 127) ch = '?';
    glyph = font_8x16[(uint8_t)ch - 32];

    lcd_set_window(x, y, x + 7, y + 15);
    for (row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                LCD_RAM = fg;
            } else {
                LCD_RAM = bg;
            }
        }
    }
}


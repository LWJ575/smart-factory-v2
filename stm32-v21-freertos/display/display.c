/* ==================== 初始化 ==================== */

void disp_init(void)
{
    /* 1. 初始化 LCD 硬件 */
    lcd_init();

    /* 2. 填充背景 */
    lcd_fill(COL_BG);

    /* 3. 绘制静态布局 */
    /* 标题 */
    lcd_show_string(8, TITLE_Y, "Smart Factory v2.1", COL_TITLE, COL_BG);
    lcd_show_string(LCD_W - 8*11, TITLE_Y, "FW " FW_VERSION, COL_LABEL, COL_BG);

    /* 分隔线 */
    lcd_draw_hline(8, LINE_Y, LCD_W - 8, COL_BORDER);

    /* 温度卡片 */
    lcd_fill_rect(TEMP_X, TEMP_Y, TEMP_X + TEMP_W, TEMP_Y + TEMP_H, COL_PANEL);
    lcd_draw_rect(TEMP_X, TEMP_Y, TEMP_X + TEMP_W, TEMP_Y + TEMP_H, COL_BORDER);
    lcd_show_string(TEMP_X + 4, TEMP_Y + 4, "Temp", COL_LABEL, COL_PANEL);

    /* 光照卡片 */
    lcd_fill_rect(LIGHT_X, LIGHT_Y, LIGHT_X + LIGHT_W, LIGHT_Y + LIGHT_H, COL_PANEL);
    lcd_draw_rect(LIGHT_X, LIGHT_Y, LIGHT_X + LIGHT_W, LIGHT_Y + LIGHT_H, COL_BORDER);
    lcd_show_string(LIGHT_X + 4, LIGHT_Y + 4, "Light", COL_LABEL, COL_PANEL);

    /* 电机卡片 */
    lcd_fill_rect(MOTOR_X, MOTOR_Y, MOTOR_X + MOTOR_W, MOTOR_Y + MOTOR_H, COL_PANEL);
    lcd_draw_rect(MOTOR_X, MOTOR_Y, MOTOR_X + MOTOR_W, MOTOR_Y + MOTOR_H, COL_BORDER);
    lcd_show_string(MOTOR_X + 4, MOTOR_Y + 4, "Motor", COL_LABEL, COL_PANEL);

    /* 状态卡片 */
    lcd_fill_rect(STATUS_X, STATUS_Y, STATUS_X + STATUS_W, STATUS_Y + STATUS_H, COL_PANEL);
    lcd_draw_rect(STATUS_X, STATUS_Y, STATUS_X + STATUS_W, STATUS_Y + STATUS_H, COL_BORDER);
    lcd_show_string(STATUS_X + 4, STATUS_Y + 4, "MQTT: --", COL_ERR, COL_PANEL);
    lcd_show_string(STATUS_X + 4, STATUS_Y + 24, "WiFi: --", COL_LABEL, COL_PANEL);

    /* 控制区 */
    lcd_fill_rect(CTRL_X, CTRL_Y, CTRL_X + CTRL_W, CTRL_Y + CTRL_H, COL_PANEL);
    lcd_draw_rect(CTRL_X, CTRL_Y, CTRL_X + CTRL_W, CTRL_Y + CTRL_H, COL_BORDER);
    lcd_show_string(CTRL_X + 4, CTRL_Y + 4, "L1:-- L2:-- Bz:--", COL_LABEL, COL_PANEL);
    lcd_show_string(CTRL_X + 4, CTRL_Y + 20, "Motor: ---", COL_LABEL, COL_PANEL);

    s_current_screen = 0;
}

/* ==================== 更新仪表盘 ==================== */

void disp_update_dashboard(void)
{
    char buf[32];

    /* 温度 */
    {
        int16_t t = g_disp_data.temp_x10;
        if (t > -9000) {
            int16_t int_part = t / 10;
            int16_t dec_part = (t < 0 ? -t : t) % 10;
            snprintf(buf, sizeof(buf), "%d.%dC", int_part, dec_part);
        } else {
            snprintf(buf, sizeof(buf), "no dev");
        }
        uint16_t color = (g_disp_data.alarm_active) ? COL_ERR : COL_TEMP;
        /* 清空旧值 */
        lcd_fill_rect(TEMP_X + 4, TEMP_Y + 30, TEMP_X + TEMP_W - 4, TEMP_Y + TEMP_H - 4, COL_PANEL);
        lcd_show_string(TEMP_X + 8, TEMP_Y + 40, buf, color, COL_PANEL);
    }

    /* 光照 */
    {
        snprintf(buf, sizeof(buf), "%4d", g_disp_data.light_raw);
        lcd_fill_rect(LIGHT_X + 60, LIGHT_Y + 4, LIGHT_X + LIGHT_W - 4, LIGHT_Y + 20, COL_PANEL);
        lcd_show_string(LIGHT_X + 60, LIGHT_Y + 4, buf, COL_LIGHT, COL_PANEL);

        /* 光照条形图 */
        uint16_t bar_w = (uint16_t)((uint32_t)g_disp_data.light_raw * (LIGHT_W - 8) / 4096);
        lcd_fill_rect(LIGHT_X + 4, LIGHT_Y + LIGHT_H - 12, LIGHT_X + LIGHT_W - 4, LIGHT_Y + LIGHT_H - 4, COL_BAR_BG);
        if (bar_w > 0) {
            lcd_fill_rect(LIGHT_X + 4, LIGHT_Y + LIGHT_H - 12, LIGHT_X + 4 + bar_w, LIGHT_Y + LIGHT_H - 4, COL_LIGHT);
        }
    }

    /* 电机 */
    {
        snprintf(buf, sizeof(buf), "%3d%%", g_disp_data.motor_speed);
        lcd_fill_rect(MOTOR_X + 60, MOTOR_Y + 4, MOTOR_X + MOTOR_W - 4, MOTOR_Y + 20, COL_PANEL);
        lcd_show_string(MOTOR_X + 60, MOTOR_Y + 4, buf, COL_MOTOR, COL_PANEL);

        /* 电机条形图 */
        uint16_t bar_w = (uint16_t)((uint32_t)g_disp_data.motor_speed * (MOTOR_W - 8) / 100);
        lcd_fill_rect(MOTOR_X + 4, MOTOR_Y + MOTOR_H - 12, MOTOR_X + MOTOR_W - 4, MOTOR_Y + MOTOR_H - 4, COL_BAR_BG);
        if (bar_w > 0) {
            lcd_fill_rect(MOTOR_X + 4, MOTOR_Y + MOTOR_H - 12, MOTOR_X + 4 + bar_w, MOTOR_Y + MOTOR_H - 4, COL_MOTOR);
        }
    }

    /* MQTT 状态 */
    {
        lcd_fill_rect(STATUS_X + 4, STATUS_Y + 4, STATUS_X + STATUS_W - 4, STATUS_Y + 16, COL_PANEL);
        if (g_disp_data.mqtt_online) {
            lcd_show_string(STATUS_X + 4, STATUS_Y + 4, "MQTT: OK", COL_OK, COL_PANEL);
        } else {
            lcd_show_string(STATUS_X + 4, STATUS_Y + 4, "MQTT: --", COL_ERR, COL_PANEL);
        }
    }

    /* 控制区 */
    {
        snprintf(buf, sizeof(buf), "L1:%s L2:%s Bz:%s",
                 g_disp_data.led1_on ? "ON " : "off",
                 g_disp_data.led2_on ? "ON " : "off",
                 g_disp_data.buzzer_on ? "ON " : "off");
        lcd_fill_rect(CTRL_X + 4, CTRL_Y + 4, CTRL_X + CTRL_W - 4, CTRL_Y + 16, COL_PANEL);
        lcd_show_string(CTRL_X + 4, CTRL_Y + 4, buf, COL_LABEL, COL_PANEL);

        snprintf(buf, sizeof(buf), "Motor: %3d%%", g_disp_data.motor_speed);
        lcd_fill_rect(CTRL_X + 4, CTRL_Y + 20, CTRL_X + CTRL_W - 4, CTRL_Y + 32, COL_PANEL);
        lcd_show_string(CTRL_X + 4, CTRL_Y + 20, buf, COL_MOTOR, COL_PANEL);
    }
}

/* ==================== OTA 屏幕 ==================== */

void disp_show_ota(uint8_t percent, const char *status)
{
    if (s_current_screen != 1) {
        /* 切换到 OTA 屏幕 */
        lcd_fill(COL_BG);
        lcd_show_string(80, 30, "Firmware Update", COL_TITLE, COL_BG);
        s_current_screen = 1;
    }

    /* 状态文本 */
    if (status) {
        lcd_fill_rect(40, 60, LCD_W - 40, 76, COL_BG);
        lcd_show_string(40, 60, status, COL_MOTOR, COL_BG);
    }

    /* 进度条背景 */
    lcd_fill_rect(OTA_BAR_X, OTA_BAR_Y, OTA_BAR_X + OTA_BAR_W, OTA_BAR_Y + OTA_BAR_H, COL_BAR_BG);
    lcd_draw_rect(OTA_BAR_X, OTA_BAR_Y, OTA_BAR_X + OTA_BAR_W, OTA_BAR_Y + OTA_BAR_H, COL_BORDER);

    /* 进度条 */
    if (percent > 0) {
        uint16_t bar_w = (uint16_t)((uint32_t)percent * OTA_BAR_W / 100);
        lcd_fill_rect(OTA_BAR_X, OTA_BAR_Y, OTA_BAR_X + bar_w, OTA_BAR_Y + OTA_BAR_H, COL_MOTOR);
    }

    /* 百分比数字 */
    char buf[8];
    snprintf(buf, sizeof(buf), "%d%%", percent);
    lcd_fill_rect(OTA_BAR_X + 80, OTA_BAR_Y + 24, OTA_BAR_X + 160, OTA_BAR_Y + 40, COL_BG);
    lcd_show_string(OTA_BAR_X + 80, OTA_BAR_Y + 24, buf, COL_TITLE, COL_BG);
}

void disp_show_dashboard(void)
{
    if (s_current_screen != 0) {
        disp_init();  /* 重绘仪表盘 */
    }
}

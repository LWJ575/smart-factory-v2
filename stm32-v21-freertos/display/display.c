{
    while (*str) {
        lcd_show_char(x, y, *str, fg, bg);
        x += 8;
        if (x + 8 > LCD_W) break;
        str++;
    }
}

/* 绘制数字 (len=显示位数, 不够前导零) */
void lcd_show_num(uint16_t x, uint16_t y, int32_t num, uint8_t len, uint16_t fg, uint16_t bg)
{
    char buf[16];
    int i;

    if (len > 15) len = 15;
    if (num < 0) {
        lcd_show_char(x, y, '-', fg, bg);
        x += 8;
        num = -num;
    }

    /* 转换为字符串 */
    snprintf(buf, sizeof(buf), "%d", (int)num);
    int slen = (int)strlen(buf);

    /* 前导空格补齐 */
    for (i = slen; i < len; i++) {
        lcd_show_char(x, y, ' ', fg, bg);
        x += 8;
    }
    for (i = 0; i < slen && i < len; i++) {
        lcd_show_char(x, y, buf[i], fg, bg);
        x += 8;
    }
}

